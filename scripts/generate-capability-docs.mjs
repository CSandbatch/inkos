#!/usr/bin/env node
/**
 * Capability registry → generated documentation, with three CI gates.
 *
 *   1. Evidence   every `shipped` capability names test files that exist
 *   2. Drift      the committed generated table matches the registry
 *   3. Shape      the registry itself is well-formed
 *
 * Gate 3 of the documentation-truth pipeline — a closed vocabulary for public
 * copy — is NOT implemented here. It is the gate that structurally prevents the
 * landing page from drifting away from reality, and it is still outstanding.
 *
 *   node scripts/generate-capability-docs.mjs            # write
 *   node scripts/generate-capability-docs.mjs --check    # verify, exit 1 on drift
 */

import { readFile, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { parseYaml } from "./lib/mini-yaml.mjs";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const REGISTRY = resolve(root, "docs/engineering/capability-registry.yaml");
const OUTPUT = resolve(root, "docs/engineering/capability-status.generated.md");
const VALID_STATUS = new Set(["shipped", "phase", "reserved"]);

const check = process.argv.includes("--check");
const problems = [];

function fail(message) {
  problems.push(message);
}

const registry = parseYaml(await readFile(REGISTRY, "utf8"));
const capabilities = registry.capabilities;

if (!capabilities || typeof capabilities !== "object") {
  console.error("capability-registry.yaml has no `capabilities` map.");
  process.exit(1);
}

const entries = Object.entries(capabilities);

for (const [id, entry] of entries) {
  const where = `capability "${id}"`;
  if (!entry || typeof entry !== "object") {
    fail(`${where}: not a map`);
    continue;
  }
  if (!entry.title) fail(`${where}: missing title`);
  if (!VALID_STATUS.has(entry.status)) {
    fail(`${where}: status "${entry.status}" is not one of ${[...VALID_STATUS].join(", ")}`);
  }
  if (entry.status === "phase" && entry.phase === undefined) {
    fail(`${where}: status "phase" requires a phase number`);
  }
  if (entry.status === "reserved" && !entry.reason) {
    fail(`${where}: status "reserved" requires a reason`);
  }

  // Gate 1. A capability cannot become `shipped` by editing YAML.
  if (entry.status === "shipped") {
    const tests = entry.evidence?.tests ?? [];
    if (tests.length === 0) {
      fail(`${where}: status "shipped" requires at least one test in evidence.tests`);
    }
    for (const path of tests) {
      if (!existsSync(resolve(root, path))) fail(`${where}: evidence test not found — ${path}`);
    }
    for (const path of entry.evidence?.docs ?? []) {
      if (!existsSync(resolve(root, path))) fail(`${where}: evidence doc not found — ${path}`);
    }
  }

  for (const adr of entry.evidence?.adrs ?? []) {
    const id4 = String(adr).padStart(4, "0");
    const matches = ["tei-is-authoritative", "separate-story-and-literary-graphs",
      "no-permanent-product-agents", "runtime-provider-separation", "human-canonical-commit",
      "hybrid-event-history", "source-available-licensing", "byo-key-first",
      "genre-neutral-platform", "oauth-device-flow"];
    const found = matches.some((slug) =>
      existsSync(resolve(root, `docs/architecture/decisions/${id4}-${slug}.md`)));
    if (!found) fail(`${where}: ADR ${id4} referenced but no matching file found`);
  }
}

if (problems.length > 0) {
  console.error("Capability registry problems:\n");
  for (const problem of problems) console.error(`  ${problem}`);
  console.error(`\n${problems.length} problem(s).`);
  process.exit(1);
}

// ── Render ───────────────────────────────────────────────────────────────────

const byStatus = { shipped: [], phase: [], reserved: [] };
for (const [id, entry] of entries) byStatus[entry.status].push([id, entry]);
byStatus.phase.sort((a, b) => (a[1].phase ?? 0) - (b[1].phase ?? 0));

const lines = [
  "<!-- GENERATED by scripts/generate-capability-docs.mjs — do not edit. -->",
  "<!-- Source: docs/engineering/capability-registry.yaml -->",
  "",
  "# Capability status",
  "",
  "What NovelGraph can do today, what is scheduled, and what is deliberately not built.",
  "",
  `Generated from ${entries.length} registry entries.`,
  "",
  "| Status | Meaning |",
  "| --- | --- |",
  "| **Shipped** | Implemented and covered by a referenced test |",
  "| **Phase N** | Designed and scheduled; not available |",
  "| **Reserved** | Deliberately designed for and deliberately not built |",
  "",
  `## Shipped (${byStatus.shipped.length})`,
  "",
  "| Capability | Summary | Evidence |",
  "| --- | --- | --- |",
];

for (const [id, entry] of byStatus.shipped) {
  const tests = (entry.evidence?.tests ?? []).length;
  lines.push(`| **${entry.title}**<br/><code>${id}</code> | ${entry.summary ?? ""} | ${tests} test file${tests === 1 ? "" : "s"} |`);
}

lines.push("", `## Scheduled (${byStatus.phase.length})`, "",
  "| Capability | Phase | Summary |", "| --- | --- | --- |");
for (const [id, entry] of byStatus.phase) {
  const blockers = entry.blockers?.length ? `<br/>*Blocked on: ${entry.blockers.join("; ")}*` : "";
  lines.push(`| **${entry.title}**<br/><code>${id}</code> | ${entry.phase} | ${entry.summary ?? ""}${blockers} |`);
}

lines.push("", `## Reserved — deliberately not built (${byStatus.reserved.length})`, "",
  "| Capability | Why |", "| --- | --- |");
for (const [id, entry] of byStatus.reserved) {
  lines.push(`| **${entry.title}**<br/><code>${id}</code> | ${entry.reason ?? ""} |`);
}

lines.push("",
  "---",
  "",
  "**A capability may not be described in the present tense in public copy unless its status",
  "here is Shipped.** Changing that status requires a passing test, not a documentation edit.",
  "");

const rendered = `${lines.join("\n")}\n`;

// ── Gate 2 ───────────────────────────────────────────────────────────────────

if (check) {
  let committed = null;
  try {
    committed = await readFile(OUTPUT, "utf8");
  } catch {
    console.error(`Missing generated file: ${OUTPUT}\nRun: pnpm capabilities:generate`);
    process.exit(1);
  }
  if (committed !== rendered) {
    console.error(
      `Generated capability status is out of date.\n` +
      `  ${OUTPUT}\nRun: pnpm capabilities:generate`,
    );
    process.exit(1);
  }
  const counts = `${byStatus.shipped.length} shipped, ${byStatus.phase.length} scheduled, ${byStatus.reserved.length} reserved`;
  console.log(`Capability registry verified — ${entries.length} entries (${counts}).`);
} else {
  await writeFile(OUTPUT, rendered, "utf8");
  console.log(`Wrote ${OUTPUT} from ${entries.length} registry entries.`);
}
